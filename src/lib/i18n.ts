export type DictKey = keyof (typeof dict)['es'];

export function getDict(lang: Lang): Record<DictKey, string> {
  return dict[lang] as unknown as Record<DictKey, string>;
}

export function translate(dict: Record<DictKey, string>, key: string, vars?: Record<string, string | number>): string {
  const template = dict[key as DictKey] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}